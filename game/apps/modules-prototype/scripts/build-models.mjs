import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Inlines models/*.glb as base64 data URIs so the single-file build
// works from file:// (no fetch, no CORS). Models: Quaternius, CC0-1.0.
const base = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const files = {
  solar: 'solar.glb',
  water: 'water.glb',
  greenhouse: 'greenhouse.glb',
  habitat: 'habitat.glb',
  node: 'node.glb',
  lab: 'lab.glb'
};

const out = {};
for (const [id, f] of Object.entries(files)) {
  const buf = fs.readFileSync(path.join(base, 'models', f));
  if (buf.slice(0, 4).toString() !== 'glTF') {
    console.error(`!! ${f} is not a GLB file`);
    process.exit(1);
  }
  out[id] = `data:model/gltf-binary;base64,${buf.toString('base64')}`;
}

const code =
  `// GENERATED by scripts/build-models.mjs — Quaternius models (CC0-1.0) inlined as data URIs.\n` +
  `export const MODEL_DATA = ${JSON.stringify(out, null, 2)};\n`;

const dest = path.join(base, 'src', 'data', 'modelData.js');
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, code);
console.log(`modelData.js: ${Object.keys(out).length} models, ${code.length} bytes`);
